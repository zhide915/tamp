const (
	// Project is the router's compose project: one per machine.
	Project = "tamp-router"
	// Container is the router's container name.
	Container = "tamp-router"
	Image     = "caddy:2.10"
	// Port is the only port the router publishes, on loopback.
	Port = 80

	// Caddyfile is the config file in the router's directory.
	Caddyfile   = "Caddyfile"
	composeFile = "compose.yaml"
	// mountDir is where the container sees the router's directory.
	mountDir = "/etc/caddy"
)

// Dir is the router's directory under the user's home.
func Dir(home string) string { return filepath.Join(home, ".tamp", "router") }

// Env is one running environment, as the router reaches it.
type Env struct {
	Name string
	// Network is the environment's network, which the router joins.
	Network string
	// Upstream is the frappe container's name on that network.
	Upstream string
	// Hosts are the site hostnames its recipe lists.
	Hosts []string
}

// Duplicate is a hostname that two environments list.
type Duplicate struct {
	Host string
	// Winner sorts first by name and gets the route.
	Winner, Loser string
}

// Resolve sorts envs by name and gives each hostname to the first that
// lists it. Each returned Env holds only the hosts routed to it.
func Resolve(envs []Env) ([]Env, []Duplicate) {
	sorted := slices.Clone(envs)
	slices.SortFunc(sorted, func(a, b Env) int { return strings.Compare(a.Name, b.Name) })
	owner := map[string]string{}
	var dups []Duplicate
	for i, e := range sorted {
		var hosts []string
		for _, h := range e.Hosts {
			switch winner, taken := owner[h]; {
			case !taken:
				owner[h] = e.Name
				hosts = append(hosts, h)
			case winner != e.Name:
				dups = append(dups, Duplicate{Host: h, Winner: winner, Loser: e.Name})
			}
		}
		sorted[i].Hosts = hosts
	}
	return sorted, dups
}

// Render is the Caddyfile for envs, already resolved.
func Render(envs []Env) []byte {
	var b bytes.Buffer
	b.WriteString("# Generated by tamp from the recipes of the running environments. Do not edit.\n")
	for _, e := range envs {
		for _, h := range e.Hosts {
			// The realtime server rejects a handshake whose Origin is not the
			// site's own, and a client need not send one.
			fmt.Fprintf(&b, `
http://%s {
	@socketio path /socket.io*
	reverse_proxy @socketio %s:%d {
		header_up Origin {scheme}://{host}
	}
	reverse_proxy %s:%d
}
`, h, e.Upstream, frappe.SocketIOPort, e.Upstream, frappe.WebPort)
		}
	}
	// Caddy answers a host no block names with an empty 200; this says why.
	// Every site block names its host, so it outranks this one.
	b.WriteString("\nhttp:// {\n\trespond \"" + NotFoundBody + "\" 404\n}\n")
	return b.Bytes()
}

// NotFoundBody is the router's answer to a hostname no running environment serves.
const NotFoundBody = "No running tamp environment serves this hostname. To see the sites, run `tamp list`."

// Router is the machine's router, reached through Docker.
type Router struct {
	Dir    string
	Docker docker.Client
	// Out receives compose's and Caddy's progress.
	Out io.Writer
}

// Apply serves envs: it replaces the Caddyfile, brings the router up when it
// is not running or its compose file changed, reloads it when it was
// running, and joins each environment's network.
func (r Router) Apply(ctx context.Context, envs []Env) error {
	if err := r.write(Caddyfile, Render(envs)); err != nil {
		return err
	}
	c, running, err := r.inspect(ctx)
	if err != nil {
		return err
	}
	var compose bytes.Buffer
	if err := composeTemplate.Execute(&compose, map[string]any{
		"Project": Project, "Container": Container, "Image": Image, "Port": Port, "Mount": mountDir,
	}); err != nil {
		return err
	}
	// A running router whose compose file changed is brought up again, so a
	// new template reaches it.
	upped := false
	if old, err := os.ReadFile(filepath.Join(r.Dir, composeFile)); !running || err != nil || !bytes.Equal(old, compose.Bytes()) {
		upped = true
		if err := r.up(ctx, compose.Bytes()); err != nil {
			return err
		}
		// A started container keeps the networks it was on when it stopped;
		// a recreated one is on none of them.
		if c, err = r.Docker.Inspect(ctx, Container); err != nil {
			return err
		}
	}
	if running {
		tries := 1
		if upped {
			tries = reloadTries
		}
		if err := r.reload(ctx, tries); err != nil {
			return err
		}
	}
	for _, e := range envs {
		if err := r.join(ctx, c, e); err != nil {
			return err
		}
	}
	return nil
}

// Reload serves envs without starting the router: it replaces the Caddyfile
// and reloads a running router. A stopped one reads the file when it starts.
func (r Router) Reload(ctx context.Context, envs []Env) error {
	if err := r.write(Caddyfile, Render(envs)); err != nil {
		return err
	}
	_, running, err := r.inspect(ctx)
	if err != nil || !running {
		return err
	}
	return r.reload(ctx, 1)
}

// Leave detaches the router from a network, if it is on it, so the network
// can be removed.
func (r Router) Leave(ctx context.Context, network string) error {
	c, err := r.Docker.Inspect(ctx, Container)
	if errors.Is(err, docker.ErrNoContainer) {
		return nil
	}
	if err != nil {
		return err
	}
	if _, on := c.Networks[network]; !on {
		return nil
	}
	return r.Docker.DisconnectNetwork(ctx, network, Container)
}

func (r Router) inspect(ctx context.Context) (docker.Container, bool, error) {
	c, err := r.Docker.Inspect(ctx, Container)
	if errors.Is(err, docker.ErrNoContainer) {
		return c, false, nil
	}
	return c, err == nil && c.Running, err
}

func (r Router) up(ctx context.Context, compose []byte) error {
	if err := r.write(composeFile, compose); err != nil {
		return err
	}
	err := r.Docker.ComposeUp(ctx, docker.Project{
		Name: Project, File: filepath.Join(r.Dir, composeFile), Out: r.Out, Publishes: true,
	})
	if errors.Is(err, docker.ErrPortTaken) {
		return PortTaken(ctx, r.Docker, fmt.Sprintf("port %d is taken, so the router cannot start", Port))
	}
	return err
}

// PortTaken is the error msg for port 80 held by something other than the
// router. Its fix names a container that publishes the port, since netstat
// shows only Docker.
func PortTaken(ctx context.Context, dc docker.Client, msg string) error {
	holders, err := dc.Publishing(ctx, Port)
	listener := fmt.Sprintf("find what listens on port %d with %s, and stop it", Port, findPortCommand())
	switch {
	case err != nil:
		// The listing's own fix is to start Docker, which answered a moment ago.
		reason := err.Error()
		if e := (*exitcode.Error)(nil); errors.As(err, &e) {
			reason = e.Msg
		}
		return exitcode.New(exitcode.CodeFailed, msg+", and Docker cannot tell which container publishes it: "+reason, listener)
	case len(holders) > 0:
		return exitcode.New(exitcode.CodeFailed, msg,
			fmt.Sprintf("stop the container that publishes port %d with `docker stop %s`", Port, strings.Join(holders, " ")))
	}
	return exitcode.New(exitcode.CodeFailed, msg, listener)
}

// Loopback is where the router publishes Port. Tests point it at a port of
// their own, so none depends on what holds this machine's port 80.
var Loopback = net.JoinHostPort("127.0.0.1", strconv.Itoa(Port))

// PortHeld reports whether something accepts connections on Loopback. It
// connects and hangs up, and so binds nothing.
func PortHeld(ctx context.Context) bool {
	d := net.Dialer{Timeout: time.Second}
	c, err := d.DialContext(ctx, "tcp", Loopback)
	if err != nil {
		return false
	}
	_ = c.Close()
	return true
}

func findPortCommand() string {
	if runtime.GOOS == "windows" {
		return fmt.Sprintf("`netstat -ano | findstr LISTENING | findstr /C:\":%d \"`", Port)
	}
	return fmt.Sprintf("`sudo lsof -nP -iTCP:%d -sTCP:LISTEN`", Port)
}

// A recreated router's admin API may not listen yet, so a reload right after
// up is tried this often, this far apart.
const (
	reloadTries = 10
	reloadWait  = 500 * time.Millisecond
)

// reload tries Caddy's reload up to tries times. It prints Caddy's JSON log
// only when the last try fails, for the error's "output above".
func (r Router) reload(ctx context.Context, tries int) error {
	var log bytes.Buffer
	var err error
	for i := range tries {
		if i > 0 {
			select {
			case <-ctx.Done():
				return ctx.Err()
			case <-time.After(reloadWait):
			}
		}
		log.Reset()
		err = r.Docker.Exec(ctx, docker.Exec{
			Container: Container,
			Cmd:       []string{"caddy", "reload", "--config", mountDir + "/" + Caddyfile, "--adapter", "caddyfile"},
			Stdout:    &log,
			Stderr:    &log,
		})
		if err == nil {
			return nil
		}
	}
	if r.Out != nil {
		_, _ = r.Out.Write(log.Bytes())
	}
	return err
}

// join attaches the router to an environment's network under its hosts as
// aliases, so a site's own URL reaches the router from inside the
// environment. Aliases are fixed at connect, so changed hosts reconnect.
func (r Router) join(ctx context.Context, c docker.Container, e Env) error {
	have, on := c.Networks[e.Network]
	if on {
		if slices.Equal(sitesOf(have), sitesOf(e.Hosts)) {
			return nil
		}
		if err := r.Docker.DisconnectNetwork(ctx, e.Network, Container); err != nil {
			return err
		}
	}
	return r.Docker.ConnectNetwork(ctx, e.Network, Container, e.Hosts)
}

// sitesOf is the sorted *.localhost aliases: older engines also list the
// container's own ID among them.
func sitesOf(aliases []string) []string {
	var out []string
	for _, a := range aliases {
		if strings.HasSuffix(a, ".localhost") {
			out = append(out, a)
		}
	}
	slices.Sort(out)
	return out
}

// write replaces a file in the router's directory by rename, so the router
// never reads half a file. The router mounts the directory, not the file: a
// file mount would keep serving the replaced file.
func (r Router) write(name string, data []byte) error {
	fail := func(err error) error {
		return exitcode.New(exitcode.CodeFailed, fmt.Sprintf("cannot write %s: %v", filepath.Join(r.Dir, name), err),
			"check that you can write to "+r.Dir)
	}
	if err := os.MkdirAll(r.Dir, 0o755); err != nil {
		return fail(err)
	}
	tmp, err := os.CreateTemp(r.Dir, name+".*.tmp")
	if err != nil {
		return fail(err)
	}
	_, err = tmp.Write(data)
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		// CreateTemp's 0600 would hide the file from a router running as
		// another user.
		err = os.Chmod(tmp.Name(), 0o644)
	}
	if err == nil {
		err = os.Rename(tmp.Name(), filepath.Join(r.Dir, name))
	}
	if err != nil {
		_ = os.Remove(tmp.Name())
		return fail(err)
	}
	return nil
}

var composeTemplate = template.Must(template.New(composeFile).Parse(`# Generated by tamp. Do not edit.
name: {{.Project}}

services:
  caddy:
    image: {{.Image}}
    container_name: {{.Container}}
    # The router outlives every environment and comes back after a reboot.
    restart: unless-stopped
    # Loopback only: *.localhost resolves there, and a development bench is
    # not served to the network.
    ports:
      - 127.0.0.1:{{.Port}}:80
    # The directory, not the file: tamp replaces the Caddyfile by rename.
    volumes:
      - .:{{.Mount}}:ro
    # Caddy keeps nothing worth keeping for plain HTTP. The tmpfs covers the
    # image's /data and /config, which would otherwise become anonymous volumes.
    tmpfs: [/data, /config]
`))
